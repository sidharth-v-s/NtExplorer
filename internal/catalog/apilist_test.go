func TestCatalogCoversListedAPIs(t *testing.T) {
	cat, _, err := catalog.Load(data.FS, ".")
	if err != nil {
		t.Fatalf("load embedded catalog: %v", err)
	}
	present := make(map[string]bool, len(cat.APIs))
	for _, api := range cat.APIs {
		present[strings.ToLower(api.Name)] = true
	}
	missing := 0
	for _, name := range strings.Fields(listedAPIs) {
		if !present[strings.ToLower(name)] {
			t.Errorf("catalog is missing %s", name)
			missing++
		}
	}
	if missing > 0 {
		t.Fatalf("%d listed APIs are missing", missing)
	}
}
