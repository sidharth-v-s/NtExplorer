func TestWriteNewDoesNotOverwrite(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "entry.json")
	if err := WriteNew(path, []byte("first")); err != nil {
		t.Fatalf("WriteNew: %v", err)
	}
	err := WriteNew(path, []byte("second"))
	if !errors.Is(err, ErrExists) {
		t.Fatalf("expected ErrExists, got %v", err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(data) != "first" {
		t.Fatalf("file was overwritten: %q", data)
	}
	if err := WriteReplace(path, []byte("replaced")); err != nil {
		t.Fatalf("WriteReplace: %v", err)
	}
}

