func TestMarkdownEscapesFenceInCode(t *testing.T) {
	api := sampleAPI()
	api.Example.Code = "// ```\nint main() { return 0; }\n// ```\n"
	md := Markdown(api)
	if !strings.Contains(md, "````cpp") {
		t.Fatalf("fence was not lengthened:\n%s", md)
	}
	if strings.Contains(md, "```\n") && !strings.Contains(md, "````\n") {
		t.Fatalf("embedded fence could terminate the code block:\n%s", md)
	}
}

